#!/usr/bin/env node
// sync-music.mjs - brings the song list of the miniVIC_music project (MiniVIC Sound) into the emulator
//
//   node scripts/sync-music.mjs            regenerates src/machines/music.ts
//   node scripts/sync-music.mjs --check    check only: exit 0 = in sync, 2 = there are differences
//   --source <folder>                      folder of the music project (default: MINIVIC_MUSIC_DIR,
//                                          then "../MiniVIC Sound" next to this repository)
//   --github                               reads from github.com/Boogs77/miniVIC_music instead of locally
//   --json                                 prints the summary as JSON
//
// The songs are played only by the MiniVIC Jukebox (public/apps/jukebox.bin, synced by sync-apps.mjs),
// which contains them all: this script copies no binary, only the list shown in the Music panel.
// Source: the song table of the music README, in the Jukebox order:
//   | 1 | In the Hall of the Mountain King | Edvard Grieg, 1875 | 75 s | `bin/mountain_king.bin` |

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MUSIC_TS = join(ROOT, 'src', 'machines', 'music.ts');
const REPO = 'Boogs77/miniVIC_music';

const args = process.argv.slice(2);
const flag = f => args.includes(f);
const opt = f => { const i = args.indexOf(f); return i >= 0 ? args[i + 1] : undefined; };
const check = flag('--check');

/** songs from the table in the music README: [{ id, title, composer, length }] */
function parseReadme(text) {
  const songs = [];
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\|\s*\d+\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*(\d+)\s*s\s*\|\s*`bin\/([\w-]+)\.bin`\s*\|/);
    if (m) songs.push({ id: m[4], title: m[1], composer: m[2], seconds: Number(m[3]) });
  }
  return songs;
}

async function readSource() {
  if (flag('--github')) {
    const headers = { 'User-Agent': 'bo6502-emulator-sync' };
    if (process.env.GITHUB_TOKEN) headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`;
    const r = await fetch(`https://raw.githubusercontent.com/${REPO}/main/README.md`, { headers });
    if (!r.ok) throw new Error(`GitHub: README.md ${r.status}`);
    return r.text();
  }
  const src = opt('--source') ?? process.env.MINIVIC_MUSIC_DIR ?? join(ROOT, '..', 'MiniVIC Sound');
  const readme = join(src, 'README.md');
  if (!existsSync(readme)) throw new Error(`music README not found: ${readme} (use --source or --github)`);
  return readFileSync(readme, 'utf8');
}

function renderMusicTs(songs) {
  const esc = s => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  return `// Songs of MiniVIC Sound (github.com/${REPO}), in the order of the MiniVIC Jukebox list.
// They are played only by the Jukebox (public/apps/jukebox.bin), which contains them all.
// List generated by scripts/sync-music.mjs: do not edit it by hand.

export interface SongInfo {
  id: string;
  title: string;
  composer: string;
  seconds: number;
}

/** the application that plays the songs */
export const JUKEBOX_FILE = 'jukebox.bin';

export const SONGS: SongInfo[] = [
${songs.map(s => `  { id: '${s.id}', title: '${esc(s.title)}', composer: '${esc(s.composer)}', seconds: ${s.seconds} },`).join('\n')}
];
`;
}

async function main() {
  const songs = parseReadme(await readSource());
  if (songs.length === 0) throw new Error('no songs found in the README table');
  const text = renderMusicTs(songs);
  const current = existsSync(MUSIC_TS) ? readFileSync(MUSIC_TS, 'utf8') : '';
  const changed = current !== text;
  if (!check && changed) writeFileSync(MUSIC_TS, text);

  const summary = { changed, total: songs.length, songs: songs.map(s => s.id) };
  if (flag('--json')) console.log(JSON.stringify(summary, null, 2));
  else if (!changed) console.log(`Song list already in sync (${songs.length}).`);
  else console.log(check ? `The song list differs (${songs.length} songs in the source).` : `Song list synced (${songs.length}).`);
  process.exit(check && changed ? 2 : 0);
}

main().catch(e => {
  console.error(`sync-music: ${e.message}`);
  process.exit(1);
});
